//! Writes the atlas out: atlas.json for tools, ATLAS.md (overview and
//! findings) and api.md (every public function and type) for people and LLM
//! agents, and deps.mmd / files.dot diagrams.
const std = @import("std");
const Allocator = std.mem.Allocator;
const Writer = std.Io.Writer;
const model = @import("model.zig");
const Config = @import("config.zig").Config;

/// Findings listed per kind in ATLAS.md; atlas.json has them all.
const max_per_kind = 30;
const max_locations = 6;

pub fn json(arena: Allocator, atlas: model.Atlas) ![]const u8 {
    var out: Writer.Allocating = .init(arena);
    try std.json.Stringify.value(atlas, .{ .whitespace = .indent_1, .emit_null_optional_fields = false }, &out.writer);
    try out.writer.writeByte('\n');
    return out.written();
}

pub fn overview(arena: Allocator, cfg: *const Config, atlas: model.Atlas) ![]const u8 {
    var out: Writer.Allocating = .init(arena);
    const w = &out.writer;
    const s = atlas.stats;

    try w.print("# Code atlas: {s}\n\n", .{cfg.name});
    try w.writeAll(
        \\Generated by zigatlas from the source; do not edit. Findings are leads, not
        \\verdicts: read the code before acting, and mute an accepted one with an
        \\`// @atlas allow: <reason>` comment above the declaration or import.
        \\
        \\
    );
    try w.print("{d} files · {d} lines · {d} functions ({d} pub) · {d} types · {d} tests · {d} imports between project files\n\n", .{
        s.files, s.lines, s.functions, s.pub_functions, s.containers, s.tests, s.import_edges,
    });
    try w.writeAll(
        \\Also here: `api.md` (every public function and type, grouped by directory: search it
        \\before writing a new helper), `atlas.json` (everything, including call edges),
        \\`deps.mmd` (directory graph, Mermaid) and `files.dot` (file graph, Graphviz).
        \\
        \\
    );

    try findingSummary(w, atlas.findings);
    try layerSection(arena, w, cfg, atlas);
    try dirSection(arena, w, atlas);
    try findingSection(w, atlas.findings);
    try hotspotSection(arena, w, atlas);
    return out.written();
}

fn findingSummary(w: *Writer, findings: []const model.Finding) !void {
    try w.writeAll("## Findings at a glance\n\n| kind | error | warn | info |\n|---|---:|---:|---:|\n");
    inline for (std.meta.fields(model.FindingKind)) |field| {
        const kind: model.FindingKind = @enumFromInt(field.value);
        var counts = [_]u32{ 0, 0, 0 };
        for (findings) |f| {
            if (f.kind == kind) counts[f.severity.rank()] += 1;
        }
        if (counts[0] + counts[1] + counts[2] > 0) {
            try w.print("| {s} | {d} | {d} | {d} |\n", .{ field.name, counts[2], counts[1], counts[0] });
        }
    }
    try w.writeAll("\n");
}

fn layerSection(arena: Allocator, w: *Writer, cfg: *const Config, atlas: model.Atlas) !void {
    if (cfg.layers.len == 0) return;
    try w.writeAll("## Layers\n\nTop to bottom; a layer may import itself and the layers below it.\n\n| layer | files | lines | imports into |\n|---|---:|---:|---|\n");
    var path_layer: std.StringHashMapUnmanaged([]const u8) = .empty;
    for (atlas.files) |f| try path_layer.put(arena, f.path, f.layer orelse "(none)");

    const names = try arena.alloc([]const u8, cfg.layers.len + 1);
    for (cfg.layers, 0..) |l, i| names[i] = l.name;
    names[cfg.layers.len] = "(none)";

    for (names) |name| {
        var files: u32 = 0;
        var lines: u32 = 0;
        var into: std.StringArrayHashMapUnmanaged(u32) = .empty;
        for (atlas.files) |f| {
            if (!std.mem.eql(u8, f.layer orelse "(none)", name)) continue;
            files += 1;
            lines += f.lines;
            for (f.imports) |imp| {
                const to = path_layer.get(imp.resolved orelse continue).?;
                const gop = try into.getOrPut(arena, to);
                gop.value_ptr.* = if (gop.found_existing) gop.value_ptr.* + 1 else 1;
            }
        }
        if (files == 0) continue;
        const thin = for (cfg.layers) |l| {
            if (std.mem.eql(u8, l.name, name)) break l.thin;
        } else false;
        try w.print("| {s}{s} | {d} | {d} | ", .{ name, if (thin) " (thin)" else "", files, lines });
        for (into.keys(), into.values(), 0..) |k, v, i| {
            try w.print("{s}{s} {d}", .{ if (i > 0) ", " else "", k, v });
        }
        try w.writeAll(" |\n");
    }
    if (cfg.forbid.len > 0) {
        try w.writeAll("\nForbidden:\n");
        for (cfg.forbid) |r| try w.print("- {s} → {s}{s}{s}\n", .{ r.from, r.to, if (r.reason.len > 0) ": " else "", r.reason });
    }
    try w.writeAll("\n");
}

const DirEdge = struct { from: []const u8, to: []const u8, count: u32 };

fn dirEdges(arena: Allocator, atlas: model.Atlas) ![]DirEdge {
    var dir_of: std.StringHashMapUnmanaged([]const u8) = .empty;
    for (atlas.files) |f| try dir_of.put(arena, f.path, f.dir);
    var counts: std.StringArrayHashMapUnmanaged(DirEdge) = .empty;
    for (atlas.files) |f| {
        for (f.imports) |imp| {
            const to = dir_of.get(imp.resolved orelse continue).?;
            if (std.mem.eql(u8, to, f.dir)) continue;
            const key = try std.fmt.allocPrint(arena, "{s}\x00{s}", .{ f.dir, to });
            const gop = try counts.getOrPut(arena, key);
            if (!gop.found_existing) gop.value_ptr.* = .{ .from = f.dir, .to = to, .count = 0 };
            gop.value_ptr.count += 1;
        }
    }
    const edges = counts.values();
    std.mem.sort(DirEdge, edges, {}, struct {
        fn less(_: void, a: DirEdge, b: DirEdge) bool {
            const o = std.mem.order(u8, a.from, b.from);
            if (o != .eq) return o == .lt;
            return b.count < a.count;
        }
    }.less);
    return edges;
}

fn dirSection(arena: Allocator, w: *Writer, atlas: model.Atlas) !void {
    try w.writeAll("## Directory dependencies\n\nImports between directories (count of import statements).\n\n");
    const edges = try dirEdges(arena, atlas);
    var current: []const u8 = "";
    for (edges) |e| {
        if (!std.mem.eql(u8, current, e.from)) {
            try w.print("{s}- `{s}` →", .{ if (current.len > 0) "\n" else "", e.from });
            current = e.from;
        } else try w.writeAll(",");
        try w.print(" `{s}` {d}", .{ e.to, e.count });
    }
    try w.writeAll("\n\n");
}

fn findingSection(w: *Writer, findings: []const model.Finding) !void {
    try w.writeAll("## Findings\n\nMost severe first. `atlas.json` lists every finding.\n");
    var i: usize = 0;
    while (i < findings.len) {
        const kind = findings[i].kind;
        const severity = findings[i].severity;
        var j = i;
        while (j < findings.len and findings[j].kind == kind and findings[j].severity == severity) j += 1;
        try w.print("\n### {s}: {s} ({d})\n\n", .{ @tagName(severity), @tagName(kind), j - i });
        for (findings[i..@min(j, i + max_per_kind)]) |f| {
            try w.print("- {s}\n", .{f.message});
            for (f.locations[0..@min(f.locations.len, max_locations)]) |loc| {
                try w.writeAll("  - ");
                try writeLocation(w, loc);
                try w.writeAll("\n");
            }
            if (f.locations.len > max_locations) try w.print("  - … {d} more\n", .{f.locations.len - max_locations});
        }
        if (j - i > max_per_kind) try w.print("- … {d} more in atlas.json\n", .{j - i - max_per_kind});
        i = j;
    }
    try w.writeAll("\n");
}

fn writeLocation(w: *Writer, loc: model.Location) !void {
    try w.print("`{s}:{d}", .{ loc.file, loc.line });
    if (loc.end_line > loc.line) try w.print("-{d}", .{loc.end_line});
    try w.writeAll("`");
    if (loc.symbol.len > 0 and !std.mem.startsWith(u8, loc.symbol, loc.file)) {
        try w.print(" ({s})", .{loc.symbol});
    } else if (std.mem.indexOfScalar(u8, loc.symbol, ':')) |c| {
        try w.print(" {s}", .{loc.symbol[c + 1 ..]});
    }
}

fn hotspotSection(arena: Allocator, w: *Writer, atlas: model.Atlas) !void {
    try w.writeAll("## Hotspots\n\n### Most complex functions\n\n| function | complexity | nesting | lines | params |\n|---|---:|---:|---:|---:|\n");
    const fns = try arena.dupe(model.Function, atlas.functions);
    std.mem.sort(model.Function, fns, {}, struct {
        fn less(_: void, a: model.Function, b: model.Function) bool {
            return a.complexity > b.complexity;
        }
    }.less);
    for (fns[0..@min(fns.len, 15)]) |f| {
        try w.print("| `{s}:{d}` {s} | {d} | {d} | {d} | {d} |\n", .{ f.file, f.line, qualifiedName(f), f.complexity, f.depth, f.lines, f.params });
    }

    const files = try arena.dupe(model.File, atlas.files);
    try w.writeAll("\n### Most imported files (fan-in): changes here ripple the furthest\n\n");
    std.mem.sort(model.File, files, {}, struct {
        fn less(_: void, a: model.File, b: model.File) bool {
            return a.fan_in > b.fan_in;
        }
    }.less);
    for (files[0..@min(files.len, 10)]) |f| try w.print("- `{s}` ← {d}\n", .{ f.path, f.fan_in });

    try w.writeAll("\n### Files importing the most (fan-out): candidates for doing too much\n\n");
    std.mem.sort(model.File, files, {}, struct {
        fn less(_: void, a: model.File, b: model.File) bool {
            return fanOut(a) > fanOut(b);
        }
    }.less);
    for (files[0..@min(files.len, 10)]) |f| try w.print("- `{s}` → {d}\n", .{ f.path, fanOut(f) });
    try w.writeAll("\n");
}

fn fanOut(f: model.File) u32 {
    var n: u32 = 0;
    for (f.imports) |imp| {
        if (imp.resolved != null) n += 1;
    }
    return n;
}

fn qualifiedName(f: model.Function) []const u8 {
    const c = std.mem.indexOfScalar(u8, f.id, ':') orelse return f.id;
    return f.id[c + 1 ..];
}

/// Every file with its public functions and types, grouped by directory.
pub fn api(arena: Allocator, cfg: *const Config, atlas: model.Atlas) ![]const u8 {
    var out: Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.print("# API map: {s}\n\nEvery file with its doc line, public types (with fields) and public functions.\nSearch here before adding a helper; reuse or move what exists instead.\n", .{cfg.name});

    var dir: []const u8 = "";
    for (atlas.files) |f| {
        if (!std.mem.eql(u8, dir, f.dir)) {
            dir = f.dir;
            try w.print("\n## {s}\n", .{dir});
        }
        try w.print("\n### {s} ({d} lines{s}{s})\n", .{ f.path, f.lines, if (f.layer != null) ", layer " else "", f.layer orelse "" });
        if (f.doc.len > 0) try w.print("{s}\n", .{f.doc});

        var private: u32 = 0;
        for (atlas.containers) |c| {
            if (!std.mem.eql(u8, c.file, f.path)) continue;
            if (!c.is_pub) {
                private += 1;
                continue;
            }
            try w.print("- {s} `{s}` :{d}", .{ c.kind, c.name, c.line });
            if (c.fields.len > 0) {
                try w.writeAll(" {");
                for (c.fields[0..@min(c.fields.len, 10)], 0..) |field, i| {
                    try w.print("{s}{s}", .{ if (i > 0) ", " else " ", field.name });
                    if (field.type.len > 0) try w.print(": {s}", .{field.type});
                }
                if (c.fields.len > 10) try w.print(", … {d} more", .{c.fields.len - 10});
                try w.writeAll(" }");
            }
            if (c.doc.len > 0) try w.print(" — {s}", .{c.doc});
            try w.writeAll("\n");
        }
        for (atlas.functions) |fun| {
            if (!std.mem.eql(u8, fun.file, f.path)) continue;
            if (!fun.is_pub) {
                private += 1;
                continue;
            }
            try w.print("- `{s}`{s}{s} :{d}", .{ fun.signature, if (fun.owner.len > 0) " in " else "", fun.owner, fun.line });
            if (fun.doc.len > 0) try w.print(" — {s}", .{fun.doc});
            try w.writeAll("\n");
        }
        if (private > 0) try w.print("- ({d} private declarations)\n", .{private});
    }
    return out.written();
}

/// Directory dependency graph, directories grouped by layer.
pub fn mermaid(arena: Allocator, cfg: *const Config, atlas: model.Atlas) ![]const u8 {
    var out: Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.writeAll("flowchart TD\n");

    var dir_layer: std.StringArrayHashMapUnmanaged([]const u8) = .empty;
    for (atlas.files) |f| {
        const gop = try dir_layer.getOrPut(arena, f.dir);
        if (!gop.found_existing) gop.value_ptr.* = f.layer orelse "";
    }
    const layer_names = try arena.alloc([]const u8, cfg.layers.len + 1);
    for (cfg.layers, 0..) |l, i| layer_names[i] = l.name;
    layer_names[cfg.layers.len] = "";
    for (layer_names) |layer| {
        if (layer.len > 0) try w.print("  subgraph layer_{s}[\"{s}\"]\n", .{ try nodeId(arena, layer), layer });
        for (dir_layer.keys(), dir_layer.values()) |d, l| {
            if (std.mem.eql(u8, l, layer)) try w.print("    {s}[\"{s}\"]\n", .{ try nodeId(arena, d), d });
        }
        if (layer.len > 0) try w.writeAll("  end\n");
    }
    for (try dirEdges(arena, atlas)) |e| {
        try w.print("  {s} -->|{d}| {s}\n", .{ try nodeId(arena, e.from), e.count, try nodeId(arena, e.to) });
    }
    return out.written();
}

/// File import graph, files clustered by directory.
pub fn dot(arena: Allocator, atlas: model.Atlas) ![]const u8 {
    var out: Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.writeAll("digraph atlas {\n  rankdir=LR;\n  node [shape=box, fontsize=10];\n");
    var dir: []const u8 = "";
    for (atlas.files) |f| {
        if (!std.mem.eql(u8, dir, f.dir)) {
            if (dir.len > 0) try w.writeAll("  }\n");
            dir = f.dir;
            try w.print("  subgraph \"cluster_{s}\" {{\n    label=\"{s}\";\n", .{ dir, dir });
        }
        try w.print("    \"{s}\" [label=\"{s}\"];\n", .{ f.path, std.fs.path.basenamePosix(f.path) });
    }
    if (dir.len > 0) try w.writeAll("  }\n");
    for (atlas.files) |f| {
        for (f.imports) |imp| {
            const to = imp.resolved orelse continue;
            try w.print("  \"{s}\" -> \"{s}\";\n", .{ f.path, to });
        }
    }
    try w.writeAll("}\n");
    return out.written();
}

fn nodeId(arena: Allocator, name: []const u8) ![]const u8 {
    const id = try arena.alloc(u8, name.len + 2);
    id[0] = 'n';
    id[1] = '_';
    for (name, id[2..]) |c, *o| o.* = if (std.ascii.isAlphanumeric(c)) c else '_';
    return id;
}
